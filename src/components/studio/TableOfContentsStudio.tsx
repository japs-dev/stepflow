import React from 'react';
import { ArrowRight, Eye } from 'lucide-react';
import { useSopStore, isDefaultStepTitle } from '../../store/useSopStore';
import { SopStep } from '../../types/sop';

export const TableOfContentsStudio: React.FC = () => {
  const { activeProject, setActiveStepId } = useSopStore();

  if (!activeProject) return null;

  const cover = activeProject.coverPage;
  const primaryColor = activeProject.theme?.primaryColor || '#0f172a';
  const accentColor = activeProject.theme?.accentColor || '#0077C8';

  const hasCover = cover?.enabled !== false;
  const totalPages = Math.max(1, (hasCover ? 1 : 0) + (cover?.showTableOfContents !== false ? 1 : 0) + activeProject.steps.length);

  const defaultFooter = activeProject.department || cover?.organization
    ? `Confidential • ${activeProject.department || cover?.organization} • Internal Use Only`
    : 'Confidential • Internal Use Only • Generated by StepFlow';
  const runningFooter = activeProject.footerText?.trim() || defaultFooter;

  const sortedSteps = [...activeProject.steps].sort((a, b) => a.order - b.order);

  return (
    <div className="w-full h-full flex flex-col overflow-y-auto bg-zinc-100/60 dark:bg-zinc-950/60 p-4 md:p-8 items-center select-none">
      <div className="text-[11px] font-semibold text-zinc-400 uppercase tracking-wider mb-2 flex items-center gap-1.5">
        <Eye className="w-3.5 h-3.5" />
        <span>Live Table of Contents Preview (A4 Aspect Ratio)</span>
      </div>

      {/* A4 Table of Contents Preview Sheet */}
      <div className="w-full max-w-[560px] aspect-[1/1.414] bg-white rounded-xl shadow-2xl overflow-hidden border border-zinc-300/80 transition-all flex flex-col justify-between select-text relative text-zinc-900">
        {/* Top Accent Ribbon (Matches PDF 4pt Accent Bar) */}
        <div
          style={{ backgroundColor: accentColor }}
          className="absolute top-0 left-0 right-0 h-1 z-10"
        />

        <div className="p-8 md:p-10 flex-1 flex flex-col">
          {/* Header Pill */}
          <div className="pt-2 mb-3">
            <div
              style={{ backgroundColor: primaryColor }}
              className="inline-flex items-center px-2.5 py-1 rounded-sm text-[9px] font-bold tracking-wider text-white uppercase shadow-xs"
            >
              TABLE OF CONTENTS
            </div>
          </div>

          {/* Title & Subtitle */}
          <div className="pb-4 mb-4 border-b border-zinc-200">
            <h1
              style={{ color: primaryColor }}
              className="text-2xl font-bold tracking-tight"
            >
              Procedure Overview
            </h1>
            <p className="text-xs text-zinc-500 mt-1">
              Comprehensive directory of sequential stages and instructional checkpoints.
            </p>
          </div>

          {/* List of Steps in Index (Matches PDF row layout) */}
          <div className="flex-1 space-y-1.5 overflow-y-auto">
            {sortedSteps.length === 0 ? (
              <div className="p-8 text-center text-xs text-zinc-400">
                No steps captured yet. Add screenshot or text steps to populate the index.
              </div>
            ) : (
              sortedSteps.map((step: SopStep, index: number) => {
                const stepNum = String(step.order).padStart(2, '0');
                const title = isDefaultStepTitle(step.title)
                  ? (step.title ? step.title.replace(/^Step\s+\d+/i, `Step ${step.order}`) : `Step ${step.order}: Action`)
                  : (step.title || `Step ${step.order}`);

                const pageNumber = hasCover ? index + 3 : index + 2;

                return (
                  <div
                    key={step.id}
                    onClick={() => setActiveStepId(step.id)}
                    className="group flex items-center justify-between py-1.5 px-2 rounded hover:bg-zinc-100/70 border-b border-zinc-100 transition-colors cursor-pointer text-xs"
                    title={`Click to view Step ${step.order}`}
                  >
                    <div className="flex items-center gap-2.5 min-w-0 flex-1 pr-2">
                      {/* Step Number Pill */}
                      <span
                        style={{ color: primaryColor }}
                        className="px-2 py-0.5 rounded-sm bg-slate-100 text-[10px] font-bold font-mono shrink-0"
                      >
                        {stepNum}
                      </span>

                      {/* Step Title */}
                      <span className="font-bold text-zinc-900 truncate group-hover:text-blue-600 transition-colors">
                        {title}
                      </span>
                    </div>

                    {/* Dotted Leader & Page Indicator */}
                    <div className="flex items-center gap-2 shrink-0">
                      <span className="hidden sm:inline font-mono text-zinc-300 tracking-widest text-[10px]">
                        . . . . . . . . . .
                      </span>
                      <span
                        style={{ color: accentColor }}
                        className="font-bold text-[11px] font-mono"
                      >
                        Page {pageNumber}
                      </span>
                      <ArrowRight className="w-3 h-3 text-zinc-400 opacity-0 group-hover:opacity-100 transition-opacity" />
                    </div>
                  </div>
                );
              })
            )}
          </div>
        </div>

        {/* Running Footer (Matches PDF Running Footer) */}
        <div className="px-8 pb-5 pt-3 border-t border-zinc-200 text-[10px] text-zinc-400 flex items-center justify-between">
          <span className="truncate max-w-[340px]">{runningFooter}</span>
          <span className="font-mono font-medium">Page {hasCover ? 2 : 1} of {totalPages}</span>
        </div>
      </div>
    </div>
  );
};
